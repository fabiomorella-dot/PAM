function FCSFit(~, ~, openNewWindow, data)

    % FCSFit
    %
    % Main callback to open an FCSFit window.
    %
    % See the README file under the FCSFit directory for documentation.

    arguments (Input)
        ~
        ~
        % If true, always create a new window.
        % If false, only create a window if none exists,
        %           otherwise focus an existing window.
        openNewWindow (1,1) logical = false
        % Data to populate the GUI state with.
        % This is only used if `openNewWindow` is true.
        data fcs.gui.class.FcsGUIData {mustBeScalarOrEmpty} = fcs.gui.class.FcsGUIData.empty
    end

    startup();

    if ~openNewWindow
        existingWindows = findobj('Tag', 'FCSFit');

        if ~isempty(existingWindows)
            % already exists, give focus to the first entry and exit
            figure(existingWindows(1));
            return
        end
    end

    [h, fig] = createFigure('FCSFit');

    h.CurrentGui = 'FCS';
    guidata(fig, h);


    % 3C-FCCS extension: adds its own menu when it is installed
    % (functions/FCSFit/+fcs3c). Without it, nothing changes.
    if ~isempty(which('fcs3c.addMenu'))
        fcs3c.addMenu(fig);
    end
    % initialize GUI state variables
    fig.UserData = fcs.gui.class.FcsGUIData();

    if isempty(data)
        % try to initialize fit and style
        fcs.gui.cb.loadFitCallback(fig, [], false);
        fcs.gui.cb.styleInitializeCallback(fig, [])
    else
        % only use the permanent, non-handle data (no plots, etc.)!
        fig.UserData.data = data.data;
        fig.UserData.meta = data.meta;

        % update the GUI, since that is not included in the state
        fcs.gui.cb.initializeFullGUI(fig, []);
    end

    % 3C-FCCS fit models: adds "Fit models" to the 3C-FCCS menu
    % (FCCS3C_Menu.m in the PAM root, models in Models/fcs/FCCS3C_*.m).
    % Called after the fit model is loaded, so the check mark is correct.
    if exist('FCCS3C_Menu', 'file')
        FCCS3C_Menu(fig);
    end
end

