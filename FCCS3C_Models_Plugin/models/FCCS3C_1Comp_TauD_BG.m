function [description, equation, parameters, brightness, fit] = FCCS3C_1Comp_TauD_BG()

    arguments (Input)
    end

    arguments (Output)
        description (1,:) char
        equation (1,:) char
        parameters (1,:) ModelParameter
        brightness (1,1) function_handle
        fit (1,1) function_handle
    end

    description = [ ...
        'One component, 3D normal diffusion model for 3C-FCCS.\n', ...
        '3C (0/1) switch, keep it fixed: 0 = autocorrelation or 2-colour cross-correlation,\n', ...
        '1 = 3-colour triple correlation on the diagonal tau1 = tau, tau2 = 2*tau (gamma = 3^-3/2).\n', ...
        'Diffusion time(s) fitted; structure parameter p = w_z/w_r free (use for calibration).\n', ...
        'One exponential triplet component (fixed to 0 by default; not used when 3C = 1).\n', ...
        'Background correction: amplitude scaled by (1-BG_a/Counts_a)(1-BG_b/Counts_b),\n', ...
        'times (1-BG_c/Counts_c) when 3C = 1. Counts and BG are inputs in kHz, keep them fixed.\n', ...
        'Autocorrelation: same channel in a and b. Channel c is only used when 3C = 1.\n', ...
    ];

    equation = '|3C switch|*|gamma|*|N|*|BG correction|*|Trip amplitude|*|Trip time|*|xy diffusion|*|z diffusion|+|Offset|';

    parameters = [ ...
        ModelParameter('is3C', '3C (0/1)', 0, 0, 1, true), ...
        ModelParameter('N', 'N', 1, 0, Inf), ...
        ModelParameter('tau_D', 'tauD[&mu;s]', 30, 0, Inf), ...
        ModelParameter('p', 'p', 5, 0, Inf), ...
        ModelParameter('tau_T', 'tauT[&mu;s]', 1, 0, Inf, true), ...
        ModelParameter('Trip', 'Trip', 0, 0, 0.99, true), ...
        ModelParameter('Counts_a', 'Counts<sub>a</sub>[kHz]', 100, 1e-09, Inf, true), ...
        ModelParameter('BG_a', 'BG<sub>a</sub>[kHz]', 0, 0, Inf, true), ...
        ModelParameter('Counts_b', 'Counts<sub>b</sub>[kHz]', 100, 1e-09, Inf, true), ...
        ModelParameter('BG_b', 'BG<sub>b</sub>[kHz]', 0, 0, Inf, true), ...
        ModelParameter('Counts_c', 'Counts<sub>c</sub>[kHz]', 100, 1e-09, Inf, true), ...
        ModelParameter('BG_c', 'BG<sub>c</sub>[kHz]', 0, 0, Inf, true), ...
        ModelParameter('y_0', 'y0', 0, -1, 1), ...
    ];

    brightness = @(is3C, N, tau_D, p, tau_T, Trip, Counts_a, BG_a, Counts_b, BG_b, Counts_c, BG_c, y_0) ...
        ((1-round(is3C))*sqrt((1-BG_a/Counts_a)*(1-BG_b/Counts_b))+round(is3C)*((1-BG_a/Counts_a)*(1-BG_b/Counts_b)*(1-BG_c/Counts_c))^(1/3))*(1/N);

    fit = @(x, is3C, N, tau_D, p, tau_T, Trip, Counts_a, BG_a, Counts_b, BG_b, Counts_c, BG_c, y_0) ...
        (1-round(is3C))*(1/sqrt(8))*(1-BG_a/Counts_a)*(1-BG_b/Counts_b)*(1/N)*(1+(Trip/(1-Trip))*exp(-x/tau_T/1e-6)) ...
        .*(1./(1+(x/(tau_D*1e-6)))).*(1./sqrt(1+(x/(p^2*tau_D*1e-6)))) ...
        +round(is3C)*(1/sqrt(27))*(1-BG_a/Counts_a)*(1-BG_b/Counts_b)*(1-BG_c/Counts_c)*(1/N^2) ...
        *(1./(1+(8/3)*(x/(tau_D*1e-6))+(4/3)*(x/(tau_D*1e-6)).^2)).*(1./sqrt(1+(8/3)*(x/(p^2*tau_D*1e-6))+(4/3)*(x/(p^2*tau_D*1e-6)).^2)) ...
        +y_0;
end
