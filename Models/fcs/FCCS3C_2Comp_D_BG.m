function [description, equation, parameters, brightness, fit] = FCCS3C_2Comp_D_BG()

    arguments (Input)
    end

    arguments (Output)
        description (1,:) char
        equation (1,:) char
        parameters (1,:) ModelParameter
        brightness (1,1) function_handle
        fit (1,1) function_handle
    end

    description = [ ...
        'Two component, 3D normal diffusion model for 3C-FCCS.\n', ...
        '3C (0/1) switch, keep it fixed: 0 = autocorrelation or 2-colour cross-correlation,\n', ...
        '1 = 3-colour triple correlation on the diagonal tau1 = tau, tau2 = 2*tau (gamma = 3^-3/2).\n', ...
        'Brightnesses of the two components are assumed to be equal.\n', ...
        'Diffusion coefficient(s) fitted; focus size w_r, w_z fixed to the calibration by default.\n', ...
        'One exponential triplet component (fixed to 0 by default; not used when 3C = 1).\n', ...
        'Background correction: amplitude scaled by (1-BG_a/Counts_a)(1-BG_b/Counts_b),\n', ...
        'times (1-BG_c/Counts_c) when 3C = 1. Counts and BG are inputs in kHz, keep them fixed.\n', ...
        'Autocorrelation: same channel in a and b. Channel c is only used when 3C = 1.\n', ...
    ];

    equation = '|3C switch|*|gamma|*|N|*|BG correction|*|Trip amplitude|*|Trip time|*|xy diffusion|*|z diffusion|+|Offset|';

    parameters = [ ...
        ModelParameter('is3C', '3C (0/1)', 0, 0, 1, true), ...
        ModelParameter('N_1', 'N1', 1, 0, Inf), ...
        ModelParameter('D_1', 'D1[&mu;m<sup>2</sup>/s]', 373, 0, Inf), ...
        ModelParameter('N_2', 'N2', 1, 0, Inf), ...
        ModelParameter('D_2', 'D2[&mu;m<sup>2</sup>/s]', 10, 0, Inf), ...
        ModelParameter('w_r', 'w<sub>r</sub>[&mu;m]', 0.2, 0, Inf, true), ...
        ModelParameter('w_z', 'w<sub>z</sub>[&mu;m]', 1, 0, Inf, true), ...
        ModelParameter('tau_T', 'tauT[&mu;s]', 1, 0, Inf, true), ...
        ModelParameter('Trip', 'Trip', 0, 0, 0.99, true), ...
        ModelParameter('Counts_a', 'Counts<sub>a</sub>[kHz]', 100, 1e-09, Inf, true), ...
        ModelParameter('BG_a', 'BG<sub>a</sub>[kHz]', 0, 0, Inf, true), ...
        ModelParameter('Counts_b', 'Counts<sub>b</sub>[kHz]', 100, 1e-09, Inf, true), ...
        ModelParameter('BG_b', 'BG<sub>b</sub>[kHz]', 0, 0, Inf, true), ...
        ModelParameter('Counts_c', 'Counts<sub>c</sub>[kHz]', 100, 1e-09, Inf, true), ...
        ModelParameter('BG_c', 'BG<sub>c</sub>[kHz]', 0, 0, Inf, true), ...
        ModelParameter('y_0', 'y0', 0, -1, 1), ...
    ];

    brightness = @(is3C, N_1, D_1, N_2, D_2, w_r, w_z, tau_T, Trip, Counts_a, BG_a, Counts_b, BG_b, Counts_c, BG_c, y_0) ...
        ((1-round(is3C))*sqrt((1-BG_a/Counts_a)*(1-BG_b/Counts_b))+round(is3C)*((1-BG_a/Counts_a)*(1-BG_b/Counts_b)*(1-BG_c/Counts_c))^(1/3))*(1/(N_1+N_2));

    fit = @(x, is3C, N_1, D_1, N_2, D_2, w_r, w_z, tau_T, Trip, Counts_a, BG_a, Counts_b, BG_b, Counts_c, BG_c, y_0) ...
        (1-round(is3C))*(1/sqrt(8))*(1-BG_a/Counts_a)*(1-BG_b/Counts_b)*(1/(N_1+N_2)^2)*(1+(Trip/(1-Trip))*exp(-x/tau_T/1e-6)) ...
        .*(N_1*(1./(1+(4*(D_1*1e-12)*x/(w_r*1e-6)^2))).*(1./sqrt(1+(4*(D_1*1e-12)*x/(w_z*1e-6)^2))) ...
        +N_2*(1./(1+(4*(D_2*1e-12)*x/(w_r*1e-6)^2))).*(1./sqrt(1+(4*(D_2*1e-12)*x/(w_z*1e-6)^2)))) ...
        +round(is3C)*(1/sqrt(27))*(1-BG_a/Counts_a)*(1-BG_b/Counts_b)*(1-BG_c/Counts_c)*(1/(N_1+N_2)^3) ...
        *(N_1*(1./(1+(8/3)*(4*(D_1*1e-12)*x/(w_r*1e-6)^2)+(4/3)*(4*(D_1*1e-12)*x/(w_r*1e-6)^2).^2)).*(1./sqrt(1+(8/3)*(4*(D_1*1e-12)*x/(w_z*1e-6)^2)+(4/3)*(4*(D_1*1e-12)*x/(w_z*1e-6)^2).^2)) ...
        +N_2*(1./(1+(8/3)*(4*(D_2*1e-12)*x/(w_r*1e-6)^2)+(4/3)*(4*(D_2*1e-12)*x/(w_r*1e-6)^2).^2)).*(1./sqrt(1+(8/3)*(4*(D_2*1e-12)*x/(w_z*1e-6)^2)+(4/3)*(4*(D_2*1e-12)*x/(w_z*1e-6)^2).^2))) ...
        +y_0;
end
