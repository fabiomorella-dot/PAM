function [description, equation, parameters, brightness, fit] = FCCS3C_1Comp_D()

    arguments (Input)
    end

    arguments (Output)
        description (1,:) char
        equation (1,:) char
        parameters (1,:) ModelParameter
        brightness (1,1) function_handle
        fit (1,1) function_handle
    end

    description = [ ...
        'One component, 3D normal diffusion model for 3C-FCCS auto- and cross-correlations.\n', ...
        'Diffusion coefficient(s) fitted; focus size w_r, w_z fixed to the calibration by default.\n', ...
        'One exponential triplet component (fixed to 0 by default).\n', ...
        'No background correction.\n', ...
    ];

    equation = '|gamma|*|N|*|Trip amplitude|*|Trip time|*|xy diffusion|*|z diffusion|+|Offset|';

    parameters = [ ...
        ModelParameter('N', 'N', 1, 0, Inf), ...
        ModelParameter('D', 'D[&mu;m<sup>2</sup>/s]', 373, 0, Inf), ...
        ModelParameter('w_r', 'w<sub>r</sub>[&mu;m]', 0.2, 0, Inf, true), ...
        ModelParameter('w_z', 'w<sub>z</sub>[&mu;m]', 1, 0, Inf, true), ...
        ModelParameter('tau_T', 'tauT[&mu;s]', 1, 0, Inf, true), ...
        ModelParameter('Trip', 'Trip', 0, 0, 0.99, true), ...
        ModelParameter('y_0', 'y0', 0, -1, 1), ...
    ];

    brightness = @(N, D, w_r, w_z, tau_T, Trip, y_0) ...
        1/N;

    fit = @(x, N, D, w_r, w_z, tau_T, Trip, y_0) ...
        (1/sqrt(8))*(1/N)*(1+(Trip/(1-Trip))*exp(-x/tau_T/1e-6)) ...
        .*(1./(1+4*(D*1e-12)*x/(w_r*1e-6)^2)).*(1./sqrt(1+4*(D*1e-12)*x/(w_z*1e-6)^2)) ...
        +y_0;
end
