function [description, equation, parameters, brightness, fit] = FCS_D_2Component_noBG()

    % FCS_D_2Component_noBG
    %
    % Two-component 3D normal-diffusion FCS / FCCS model with one exponential
    % triplet term and an offset, WITHOUT background correction.
    %
    % This replaces the earlier variant that carried Counts_a, BG_a, Counts_b,
    % BG_b and multiplied the amplitude by (1-BG_a/Counts_a)*(1-BG_b/Counts_b).
    % Those four parameters are removed; the fitted N1/N2 are therefore the
    % apparent (background-uncorrected) particle numbers.
    %
    % Usage: copy this file into <PAM root>/Models/fcs/ and restart FCSFit.

    arguments (Input)
    end

    arguments (Output)
        description (1,:) char
        equation (1,:) char
        parameters (1,:) ModelParameter
        brightness (1,1) function_handle
        fit (1,1) function_handle
    end

    description = [ ...
        'Two component, 3D normal diffusion FCS/FCCS model.\n', ...
        'Brightnesses are assumed to be equal.\n', ...
        'Diffusion coefficients fitted, focus size (w_r, w_z) fixed to calibration.\n', ...
        'One exponential triplet component.\n', ...
        'No background correction.\n', ...
    ];

    equation = '|gamma|*|N|*|Trip amplitude|*|Trip time|*|xy diffusion|*|z diffusion|+|Offset|';

    parameters = [ ...
        ModelParameter('N_1', 'N1', 1, 0, Inf), ...
        ModelParameter('D_1', 'D1[&mu;m<sup>2</sup>/s]', 373, 0, Inf), ...
        ModelParameter('N_2', 'N2', 1, 0, Inf), ...
        ModelParameter('D_2', 'D2[&mu;m<sup>2</sup>/s]', 10, 0, Inf), ...
        ModelParameter('w_r', 'w<sub>r</sub>[&mu;m]', 0.2, 0, Inf, true), ...
        ModelParameter('w_z', 'w<sub>z</sub>[&mu;m]', 1, 0, Inf, true), ...
        ModelParameter('tau_T', 'tauT[&mu;s]', 1, 0, Inf, true), ...
        ModelParameter('Trip', 'Trip', 0, 0, 0.99, true), ...
        ModelParameter('y_0', 'y0', 0, -1, 1), ...
    ];

    brightness = @(N_1, D_1, N_2, D_2, w_r, w_z, tau_T, Trip, y_0) ...
        1/(N_1+N_2);

    fit = @(x, N_1, D_1, N_2, D_2, w_r, w_z, tau_T, Trip, y_0) ...
        y_0+(1/sqrt(8))*1/(N_1+N_2).^2*(1+((Trip/(1-Trip)*exp(-x/tau_T/1e-6)))) ...
        .*((N_1*(1./(1+4*(D_1*1e-12)*x/(w_r*1e-6)^2)).*(1./sqrt(1+4*(D_1*1e-12)*x/(w_z*1e-6)^2))) ...
        +(N_2*(1./(1+4*(D_2*1e-12)*x/(w_r*1e-6)^2)).*(1./sqrt(1+4*(D_2*1e-12)*x/(w_z*1e-6)^2))));
end
