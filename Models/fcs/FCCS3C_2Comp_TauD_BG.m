function [description, equation, parameters, brightness, fit] = FCCS3C_2Comp_TauD_BG()

    arguments (Input)
    end

    arguments (Output)
        description (1,:) char
        equation (1,:) char
        parameters (1,:) ModelParameter
        brightness (1,1) function_handle
        fit (1,1) function_handle
    end

    description = [ ...
        'Two component, 3D normal diffusion model for 3C-FCCS auto- and cross-correlations.\n', ...
        'Brightnesses of the two components are assumed to be equal.\n', ...
        'Diffusion time(s) fitted; structure parameter p = w_z/w_r fixed to the calibration by default.\n', ...
        'One exponential triplet component (fixed to 0 by default).\n', ...
        'Background correction: amplitude scaled by (1-BG_a/Counts_a)(1-BG_b/Counts_b).\n', ...
        'Enter the measured count rate and background of channel a and b and keep them fixed.\n', ...
        'For an autocorrelation enter the same channel in a and b.\n', ...
    ];

    equation = '|gamma|*|N|*|BG correction|*|Trip amplitude|*|Trip time|*|xy diffusion|*|z diffusion|+|Offset|';

    parameters = [ ...
        ModelParameter('N_1', 'N1', 1, 0, Inf), ...
        ModelParameter('tau_D_1', 'tauD1[&mu;s]', 30, 0, Inf), ...
        ModelParameter('N_2', 'N2', 1, 0, Inf), ...
        ModelParameter('tau_D_2', 'tauD2[&mu;s]', 1000, 0, Inf), ...
        ModelParameter('p', 'p', 5, 0, Inf, true), ...
        ModelParameter('tau_T', 'tauT[&mu;s]', 1, 0, Inf, true), ...
        ModelParameter('Trip', 'Trip', 0, 0, 0.99, true), ...
        ModelParameter('Counts_a', 'Counts<sub>a</sub>[kHz]', 100, 1e-09, Inf, true), ...
        ModelParameter('BG_a', 'BG<sub>a</sub>[kHz]', 0, 0, Inf, true), ...
        ModelParameter('Counts_b', 'Counts<sub>b</sub>[kHz]', 100, 1e-09, Inf, true), ...
        ModelParameter('BG_b', 'BG<sub>b</sub>[kHz]', 0, 0, Inf, true), ...
        ModelParameter('y_0', 'y0', 0, -1, 1), ...
    ];

    brightness = @(N_1, tau_D_1, N_2, tau_D_2, p, tau_T, Trip, Counts_a, BG_a, Counts_b, BG_b, y_0) ...
        sqrt((1-BG_a/Counts_a)*(1-BG_b/Counts_b))*(1/(N_1+N_2));

    fit = @(x, N_1, tau_D_1, N_2, tau_D_2, p, tau_T, Trip, Counts_a, BG_a, Counts_b, BG_b, y_0) ...
        (1/sqrt(8))*(1/(N_1+N_2)^2)*(1-BG_a/Counts_a)*(1-BG_b/Counts_b)*(1+(Trip/(1-Trip))*exp(-x/tau_T/1e-6)) ...
        .*(N_1*(1./(1+x/(tau_D_1*1e-6))).*(1./sqrt(1+(1/p^2)*x/(tau_D_1*1e-6))) ...
        +N_2*(1./(1+x/(tau_D_2*1e-6))).*(1./sqrt(1+(1/p^2)*x/(tau_D_2*1e-6)))) ...
        +y_0;
end
