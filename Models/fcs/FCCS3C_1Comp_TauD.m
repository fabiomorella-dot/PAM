function [description, equation, parameters, brightness, fit] = FCCS3C_1Comp_TauD()

    arguments (Input)
    end

    arguments (Output)
        description (1,:) char
        equation (1,:) char
        parameters (1,:) ModelParameter
        brightness (1,1) function_handle
        fit (1,1) function_handle
    end

    description = [ ...
        'One component, 3D normal diffusion model for 3C-FCCS auto- and cross-correlations.\n', ...
        'Diffusion time(s) fitted; structure parameter p = w_z/w_r free (use for calibration).\n', ...
        'One exponential triplet component (fixed to 0 by default).\n', ...
        'No background correction.\n', ...
    ];

    equation = '|gamma|*|N|*|Trip amplitude|*|Trip time|*|xy diffusion|*|z diffusion|+|Offset|';

    parameters = [ ...
        ModelParameter('N', 'N', 1, 0, Inf), ...
        ModelParameter('tau_D', 'tauD[&mu;s]', 30, 0, Inf), ...
        ModelParameter('p', 'p', 5, 0, Inf), ...
        ModelParameter('tau_T', 'tauT[&mu;s]', 1, 0, Inf, true), ...
        ModelParameter('Trip', 'Trip', 0, 0, 0.99, true), ...
        ModelParameter('y_0', 'y0', 0, -1, 1), ...
    ];

    brightness = @(N, tau_D, p, tau_T, Trip, y_0) ...
        1/N;

    fit = @(x, N, tau_D, p, tau_T, Trip, y_0) ...
        (1/sqrt(8))*(1/N)*(1+(Trip/(1-Trip))*exp(-x/tau_T/1e-6)) ...
        .*(1./(1+x/(tau_D*1e-6))).*(1./sqrt(1+(1/p^2)*x/(tau_D*1e-6))) ...
        +y_0;
end
