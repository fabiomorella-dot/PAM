"""Reading and writing simulation results.

``save_sim`` writes the same variables as Sim.m (``Sim_Photons`` and
``Header``), so the file opens in PAM via *Load TCSPC data -> Pam Simulation
Files*.  Sim.m saves with ``-v7.3``; here a MATLAB v5 MAT file is written,
which ``load(...,'-mat')`` in PAM reads just the same.  A v5 variable must
stay below 4 GB, so very large results are split into several files.
"""

from __future__ import annotations

import os

import numpy as np

IRF_TIME_S = 600     # Sim.m: 600 second IRF measurement
N_IRF = 1_000_000    # Sim.m: number of IRF photons per colour and channel
SCATTER_TIME_S = 600


def general_struct(settings, seed=None):
    """``SimData.General``-like struct (MATLAB field names)."""
    seed = settings.seed if seed is None else seed
    g = {
        "Name": settings.name, "BS": np.asarray(settings.box_size, float),
        "Seed": float(seed) if seed is not None else -1.0,
        "SeedString": str(seed),
        "Freq": float(settings.freq), "SimTime": float(settings.sim_time),
        "Frames": float(settings.frames), "Px": np.asarray(settings.pixels, float),
        "Size": np.asarray(settings.pixel_size, float), "Time": np.asarray(settings.times, float),
        "ScanType": float(settings.scan_type), "UseNoise": float(settings.use_noise),
        "Noise": np.asarray(settings.noise, float), "MIRange": float(settings.mi_range),
        "IRFwidth": float(settings.irf_width), "HeterogeneityUpdate": float(settings.heterogeneity_update),
        "LinkerWidth": float(settings.linker_width),
        "DynamicRate": np.asarray(settings.dynamic_rates if settings.dynamic_rates is not None else 0.0, float),
        "Generator": "pamsim (Python)",
    }
    return g


def species_struct(sp):
    return {
        "Name": sp.name, "Color": float(sp.color), "FRET": float(sp.fret), "Barrier": float(sp.barrier),
        "D": float(sp.D), "N": float(sp.N), "wr": sp.wr, "wz": sp.wz, "dX": sp.dX, "dY": sp.dY,
        "dZ": sp.dZ, "ExP": sp.ExP, "Cross": sp.Cross, "DetP": sp.DetP, "BlP": sp.BlP,
        "UseLT": float(sp.use_lt), "LT": sp.LT, "R0": sp.R0, "R": sp.R,
        "DistanceWidth": sp.distance_width, "Aniso": sp.aniso,
    }


def _cell(mts, mis):
    cell = np.empty((len(mts), 2), dtype=object)
    for i, (m, u) in enumerate(zip(mts, mis)):
        cell[i, 0] = np.asarray(m, np.float64).reshape(-1, 1)
        cell[i, 1] = np.asarray(u, np.uint16).reshape(-1, 1)
    return cell


def make_irf(result, rng=None):
    """IRF photons as generated by Sim.m (advanced mode)."""
    rng = rng or np.random.default_rng()
    info = result._kernel_info
    mi_bins = info["mi_bins"]
    t_mt = IRF_TIME_S * result.freq_hz
    mts, mis = [], []
    for _ in range(result.n_channels):
        mt = np.concatenate([np.floor(np.linspace(1, t_mt, N_IRF))] * 4)
        mi = np.concatenate([rng.normal(info["irf_mean"] + j * (mi_bins // 4), info["irf_sd"], N_IRF)
                             for j in range(4)])
        mi = np.mod(np.round(mi), mi_bins)
        order = np.argsort(mt, kind="stable")
        mts.append(mt[order]); mis.append(mi[order].astype(np.uint16))
    return mts, mis


def make_scatter(result, rng=None):
    """Uniform scatter/background pattern as generated by Sim.m (advanced mode)."""
    rng = rng or np.random.default_rng()
    mi_bins = result._kernel_info["mi_bins"]
    s = result.settings
    noise = np.asarray(s.noise, float) if s.use_noise else np.full(4, 1e-6)
    mts, mis = [], []
    for c in range(result.n_channels):
        n = int(np.floor(SCATTER_TIME_S * 1000 * noise[c % 4]))
        mts.append(np.floor(np.linspace(1, IRF_TIME_S * result.freq_hz, n)))
        mis.append(rng.integers(1, mi_bins + 1, n).astype(np.uint16))
    return mts, mis


def _write(path, mts, mis, header):
    from scipy.io import savemat
    savemat(path, {"Sim_Photons": _cell(mts, mis), "Header": header},
            appendmat=False, do_compression=True, oned_as="column")


#: A MAT v5 variable must stay below 2**32 bytes; Sim_Photons needs about
#: 10 bytes per photon (float64 macrotime + uint16 microtime).
MAX_SIM_BYTES = 3.5e9


def _split_parts(result, max_bytes):
    """Cut the photons into time blocks that each fit into one MAT v5 file.

    Returns a list of (macrotimes, microtimes, header) per part.  Parts are
    whole frames where possible (else equal time blocks); macrotimes start
    at 0 in every part, so PAM can load all parts together as consecutive files.
    """
    n_bytes = sum(m.size * 10 + 256 for m in result.macrotimes)
    n_parts = max(1, int(np.ceil(n_bytes / max_bytes)))
    h0 = result.header
    frames, frame_ticks = int(h0["Frames"]), float(h0["FrameTime"])
    if n_parts == 1:
        return [(result.macrotimes, result.microtimes, h0)]
    if frames >= n_parts:
        per = int(np.ceil(frames / n_parts))
        blocks = [(k * per, min(frames, (k + 1) * per)) for k in range(int(np.ceil(frames / per)))]
        edges = [(a * frame_ticks, b * frame_ticks, b - a, frame_ticks) for a, b in blocks]
    else:
        total = frames * frame_ticks
        length = np.ceil(total / n_parts)
        edges = [(k * length, min(total, (k + 1) * length), 1, min(total, (k + 1) * length) - k * length)
                 for k in range(n_parts)]
    parts = []
    for lo, hi, n_frames, ft in edges:
        mts, mis = [], []
        for m, u in zip(result.macrotimes, result.microtimes):
            a, b = np.searchsorted(m, [lo, hi], side="left")
            mts.append(m[a:b] - lo)
            mis.append(u[a:b])
        h = dict(h0)
        h["Frames"] = float(n_frames)
        h["FrameTime"] = float(ft)
        parts.append((mts, mis, h))
    return parts


def save_sim(result, path, irf=None, scatter=None, max_bytes=MAX_SIM_BYTES):
    """Write ``path`` (and ``*_irf.sim`` / ``*_scat.sim`` like Sim.m).

    Results that are too large for one MAT v5 file (more than ~350 million
    photons) are split in time into ``<name>_part01.sim``, ``_part02.sim``,
    ...; select all parts together when loading them in PAM.
    Returns the list of written files.
    """
    path = os.fspath(path)
    base = path[:-4] if path.endswith(".sim") else path
    parts = _split_parts(result, max_bytes)
    if len(parts) == 1:
        written = [path]
        _write(path, *parts[0])
    else:
        written = []
        for k, (mts, mis, h) in enumerate(parts, start=1):
            name = f"{base}_part{k:02d}.sim"
            _write(name, mts, mis, h)
            written.append(name)
    advanced = result.mode == "advanced"
    if irf is None:
        irf = advanced
    if scatter is None:
        scatter = advanced and result.settings.use_noise
    rng = np.random.default_rng(np.random.SeedSequence(result._kernel_info.get("seed", 0), spawn_key=(2 ** 31 + 1,)))
    if irf:
        h = dict(result.header)
        h["FrameTime"] = float(IRF_TIME_S * result.freq_hz / result.header["Frames"])
        mts, mis = make_irf(result, rng)
        _write(base + "_irf.sim", mts, mis, h)
        written.append(base + "_irf.sim")
        if scatter:
            h = dict(result.header)
            h["FrameTime"] = float(SCATTER_TIME_S * result.freq_hz / result.header["Frames"])
            mts, mis = make_scatter(result, rng)
            _write(base + "_scat.sim", mts, mis, h)
            written.append(base + "_scat.sim")
    return written


def load_sim(path):
    """Read a ``.sim`` file written by :func:`save_sim` (MAT v5).

    Returns ``(macrotimes, microtimes, header)`` with lists per channel.
    """
    from scipy.io import loadmat
    try:
        d = loadmat(path, simplify_cells=True)
    except NotImplementedError as err:
        raise ValueError(f"{path} is a MATLAB -v7.3 (HDF5) file as written by Sim.m; "
                         "re-save it in MATLAB with save(...,'-v7') to read it here") from err
    cell = d["Sim_Photons"]
    mts = [np.asarray(cell[i][0], float).ravel() for i in range(len(cell))]
    mis = [np.asarray(cell[i][1]).ravel() for i in range(len(cell))]
    return mts, mis, d["Header"]


def save_npz(result, path):
    arrays = {}
    for c in range(result.n_channels):
        arrays[f"macrotimes_{c}"] = result.macrotimes[c]
        arrays[f"microtimes_{c}"] = result.microtimes[c]
        arrays[f"labels_{c}"] = result.labels[c]
    arrays["freq_hz"] = result.freq_hz
    arrays["mi_bins"] = result.header["MI_Bins"]
    arrays["frame_ticks"] = result.header["FrameTime"]
    arrays["frames"] = result.header["Frames"]
    np.savez_compressed(path, **arrays)
    return path
